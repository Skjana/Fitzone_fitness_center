        <h2>Stress Relief Techniques</h2>
        <p>These proven methods can help manage stress and anxiety effectively.</p>
        
        <ul class="exercise-list">
            <li class="exercise-item">
                <h4>Deep Breathing Exercise</h4>
                <p>Practice 4-7-8 breathing: Inhale for 4 seconds, hold for 7, exhale for 8. Repeat 5 times.</p>
            </li>
            <li class="exercise-item">
                <h4>Progressive Muscle Relaxation</h4>
                <p>Systematically tense and relax muscle groups from toes to head. Hold tension for 5 seconds.</p>
            </li>
            <li class="exercise-item">
                <h4>Mindful Grounding</h4>
                <p>Use the 5-4-3-2-1 technique: Notice 5 things you see, 4 you feel, 3 you hear, 2 you smell, 1 you taste.</p>
            </li>
